const FALLBACK: IconPair = { solid: MoreHorizontalCircle01Solid, stroke: MoreHorizontalCircle01Icon };

function resolve(name: string | null | undefined): IconPair {
    return (name ? REGISTRY.get(name) : undefined) ?? FALLBACK;
}

export type CategoryIconType = "stroke" | "solid";

interface CategoryIconProps {
    color: string;
    name: string | null | undefined;
    size?: number;
    /** Ignored for `solid`: a filled path has no outline to widen, so a stroke only thickens its edges into mush. */
    strokeWidth?: number;
    type?: CategoryIconType;
}

export function CategoryIcon({ name, color, size = 18, type = "solid", strokeWidth = 1.8 }: CategoryIconProps) {
    const pair = resolve(name);
    const solid = type === "solid";
    return (
        <HugeiconsIcon
            color={color}
            icon={solid ? pair.solid : pair.stroke}
            size={size}
            strokeWidth={solid ? undefined : strokeWidth}
        />
    );
}
